    chip(s, 0.7, 6.0, 4.2, '不想回答的问题，说“跳过”就可以', fill=None, line=CORAL, color=CORAL)
    timeline(s, [('同桌互问', 2), ('举牌', 1), ('今日问题', 1)], y=6.5)
    notes(s, '对应教材 P38 课堂小调查（教材原要求4人一组、每人问5位同学并汇总；本课压缩为同桌互问2′＋举牌1′）。\n举牌：第①问 A英文名／B中文名／C看场合；只数人数，不评价，不追问“为什么不喜欢中文名”。\n安全提醒：名字、家庭语言属于个人信息；任何问题都可以说“跳过”；不要求说出家庭情况；不比较哪种名字更好；不评价具体同学的民族或家庭。\n预期：多数选C。可追问“看什么场合？”——这正是课文要谈的“语言与身份”。\n压缩：只问第①问和第③问。')

    # ---- 钩子：对话
    s = new('ink')
    T(s, 0.8, 0.5, 6, 0.3, '开场 · 先读，不回答', 12, AMBER, True)
    chip(s, 0.8, 0.95, 3.1, '两个人全程说的是英语', line=TEAL_L, color=TEAL_L)
    a1 = oval(s, 0.8, 1.7, 0.62, 0.62, fill=TEAL); label(a1, [('记者', 12, WHITE, True)])
    b1 = rrect(s, 1.6, 1.62, 7.3, 1.12, fill=INK2, line=TEAL, r=0.22)
    text(None, 0, 0, 0, 0, [('“您知道我们是华文报，因此要请教您的华文名字，以便刊登。”', 19, WHITE)], shp=b1, anchor=MID, margin=0.22)
    a2 = oval(s, W - 1.42, 3.1, 0.62, 0.62, fill=AMBER); label(a2, [('他', 14, INK, True, DISPLAY)])
    b2 = rrect(s, 4.1, 2.95, 7.55, 1.02, fill=AMBER, r=0.22)
    text(None, 0, 0, 0, 0, [('“我没有华文名字。”', 34, INK, True, DISPLAY)], shp=b2, anchor=MID, margin=0.3)
    sub = T(s, 4.2, 4.03, 7.4, 0.3, '他回答得很干脆。', 13, AMBER, align=R)
    a3 = oval(s, 0.8, 4.55, 0.62, 0.62, fill=TEAL); label(a3, [('记者', 12, WHITE, True)])
    b3 = rrect(s, 1.6, 4.47, 5.2, 0.78, fill=INK2, line=TEAL, r=0.22)
    text(None, 0, 0, 0, 0, [('（记者有点犯难……）', 17, TEAL_L)], shp=b3, anchor=MID, margin=0.22)
    a4 = oval(s, W - 1.42, 5.4, 0.62, 0.62, fill=AMBER); label(a4, [('他', 14, INK, True, DISPLAY)])
    b4 = rrect(s, 5.1, 5.3, 6.55, 0.84, fill=AMBER, r=0.22)
    text(None, 0, 0, 0, 0, [('“那你就随便给我写一个吧！”', 21, INK, True, DISPLAY)], shp=b4, anchor=MID, margin=0.3)
    q = T(s, 0.8, 6.55, 11.7, 0.5, '凭“我没有华文名字”这一句，能断定他不认同自己是华人吗？先不回答，读完全文再来。', 14, MUTED)
    reveal(s, [[a1, b1], [a2, b2, sub], [a3, b3], [a4, b4], [q]])
    notes(s, '课文开头的采访对话（点击一句一句出现）。\n只读，不回答：把今天的核心问题交给学生——“凭‘我没有华文名字’这一句，能断定他不认同自己是华人吗？”\n注意：作者说两人“说的是英语”，“他回答得很干脆”，记者“有点犯难”，他“宽慰地说”——这些词在议环节会用到。')

    # ---- 读
    s = new('paper')
    chrome(s, '第 1 课　读', '默读全文：边读边猜八个词', cur='读', mins=12)
    for i, (t1, t2) in enumerate([('猜', '读到词卡上的词：看前后句，写一个近义词，圈出帮你猜的线索词'), ('划', '用波浪线画出最让你有感觉的一句，旁边写一个字：为什么')]):
        y = 1.95 + i * 1.5
        card(s, 0.7, y, 5.0, 1.28, r=0.1)
        num(s, 0.92, y + 0.3, 0.68, t1, TEAL if i == 0 else CORAL, 22)
        T(s, 1.8, y + 0.2, 3.7, 0.9, t2, 15, TEXT_D, anchor=MID, spacing=1.3)
    text(s, 0.7, 5.0, 5.0, 0.8, [[('产出　', 13, CORAL, True), ('八个词的“近义词＋线索词”；一句画线句＋原因', 13, TEXT_D)]], spacing=1.3)
    words = ['柱倾梁塌', '门庭冷落', '山高水远', '顺水推舟', '络绎不绝', '古稀老人', '精湛', '逃遁']
    rots = [-2.0, 1.5, -1.0, 2.0, 1.2, -1.8, 1.6, -1.2]
    for i, w in enumerate(words):
        col, row = i % 2, i // 2
        x = 6.35 + col * 3.3; y = 1.85 + row * 1.12
        card(s, x, y, 3.05, 0.98, r=0.1, rot=rots[i])
        rrect(s, x, y, 0.14, 0.98, fill=AMBER, r=0.5, rot=rots[i])
        T(s, x + 0.3, y + 0.08, 2.6, 0.55, w, 24, TEXT_D, True, DISPLAY)
        T(s, x + 0.3, y + 0.62, 2.6, 0.3, '我猜：________　线索：____', 10, GREY)
    timeline(s, [('默读猜词', 8), ('同桌核对', 4)], cur=0)
    notes(s, '目的：读通全文，并留下自己的第一反应。\n默读（8′）只做两件事：①读到八个词时，看前后句，写一个熟悉的近义词或短语，并圈出帮你猜的线索词；②用波浪线画出最让你有感觉的一句（P44 活动二①）。\n支持：“读不通”的词先标记，不当场查词典。\n同桌（4′）见下一页。\n压缩：只核对自己猜错的词，最多3个。')

    # ---- 读·核对
    s = new('paper')
    chrome(s, '第 1 课　读 · 同桌核对', '先互相说“我猜的意思＋线索词”，再点一下对照', cur='读', mins=12, size=26)
    key = [('柱倾梁塌', '夸张：形容冲击大，像要把会馆震塌', '“震得”“平静”'), ('门庭冷落', '门前冷清，没有人来', '“抖掉了华语……姓氏”'),
           ('山高水远', '距离远，在这里指心理上的隔阂', '“一个屋顶之下”'), ('顺水推舟', '顺着形势办事，不费力', '“把基座移植过来”'),
           ('络绎不绝', '人来人往，连续不断', '“求他做头发造型的小姐”'), ('古稀老人', '七十岁左右的老人', '“旧屋门口”“闲坐”'),
           ('精湛', '（技艺）精深高明', '“对华人黑发造型有……研究”'), ('逃遁', '逃走，躲开', '“一开口就知道你是哪儿人”')]
    ans = []
    for i, (w, m, clue) in enumerate(key):
        col, row = i % 4, i // 4
        x = 0.7 + col * 3.02; y = 1.8 + row * 2.05
        card(s, x, y, 2.88, 1.92, r=0.08)
        rrect(s, x, y, 2.88, 0.1, fill=[TEAL, AMBER_D, CORAL, BROWN][col], r=0.5)
        T(s, x + 0.2, y + 0.2, 2.5, 0.55, w, 23, TEXT_D, True, DISPLAY)
        a = text(s, x + 0.2, y + 0.82, 2.5, 1.2, [(m, 12.5, TEAL, True), (f'线索：{clue}', 10.5, GREY)], spacing=1.35)
        ans.append(a)
    reveal(s, [ans])
    T(s, 0.7, 5.95, 11, 0.4, '猜错的词：写下“我被哪个词误导了”。然后用 2′ 互读自己画线的一句，说原因。', 12.5, TEXT_D)
    timeline(s, [('默读猜词', 8), ('同桌核对', 4)], cur=1)
    notes(s, '同桌（4′）：先互相说“我猜的意思＋我靠的线索词”（2′），再点一下对照屏幕上的词义，把猜错的词改正，并写下“我当时被哪个词误导了”；再互读自己画线的一句，说原因（2′）。\n词义依据课文语境：柱倾梁塌（夸张）、门庭冷落（会馆）、山高水远（话剧一家人）、顺水推舟（新加坡改换语言氛围）、络绎不绝（小姐们）、古稀老人（牛车水）、精湛（发型师）、逃遁（口音难以逃脱）。')

    # ---- 议·问题页
    s = new('teal')
    T(s, 0.7, 0.42, 6, 0.3, '第 1 课　议', 12, AMBER, True)
    tracker(s, '议', 15, dark=True)
    text(s, 8.9, -0.35, 4.4, 5.2, [('？', 300, WHITE, True, DISPLAY, 9)], align=C)
    text(s, 0.7, 1.2, 10.8, 2.6, [[('凭“我没有华文名字”这一句，', 42, WHITE, True, DISPLAY)],
                                  [('能断定他', 42, WHITE, True, DISPLAY), ('不认同自己是华人', 42, AMBER, True, DISPLAY), ('吗？', 42, WHITE, True, DISPLAY)]], spacing=1.3)
    for i, (Lt, t, col) in enumerate([('A', '能', CORAL), ('B', '不能', TEAL_L), ('C', '不确定', AMBER)]):
        x = 0.7 + i * 3.1
        rrect(s, x, 3.95, 2.85, 1.55, fill=INK, alpha=55, line=col, lw=2, r=0.12)
        T(s, x + 0.25, 4.05, 1.0, 1.3, Lt, 66, col, True, DISPLAY, anchor=MID)
        T(s, x + 1.2, 4.05, 1.55, 1.3, t, 30, WHITE, True, DISPLAY, anchor=MID)
    text(s, 10.15, 3.95, 2.5, 1.55, [('先写一个“依据词”，', 14, TEAL_L), ('再同时举牌。', 14, TEAL_L), ('不确定也是答案。', 14, AMBER, True)], anchor=MID, spacing=1.4)
    timeline(s, [('先立场', 2), ('找证据', 4), ('轮讲', 4), ('全班追问', 5)], dark=True)
    notes(s, '第1步 先写后站（2′）：选 A能／B不能／C不确定，写一个依据词，同时举牌。\n要点：没有举牌用手指1–3；“不确定”是合理答案。\n下面三页依次是：领场景找证据（2、3步）→ 同心圈（场景B）→ 全班追问（第4步）。')

    # ---- 议·领场景
    s = new('paper')
    chrome(s, '第 1 课　议 · 找证据、轮讲', '一人一个场景：找一条证据，标上它是哪一类', cur='议', mins=15, size=28)
    scenes = [('A', '采访与会馆', TEAL, '“我没有华文名字”……“一开口就知道你是哪儿人”', '柱倾梁塌　逃遁'), ('B', '软化与“抽象人”', AMBER_D, '“抖掉了华语……抖掉了姓氏”“斩断根脉”', '门庭冷落'),
              ('C', '话剧与现实选择', CORAL, '“每一次翻译都是一次……剥落”“无可奈何”', '山高水远　顺水推舟'), ('D', '发型师与牛车水', BROWN, '“心甘情愿的痛苦”“水……！”', '精湛　络绎不绝　古稀老人')]
    for i, (Lt, nm, col, ex, wd) in enumerate(scenes):
        x = 0.7 + i * 3.02
        card(s, x, 1.75, 2.88, 2.45, r=0.08)
        top = rrect(s, x, 1.75, 2.88, 0.62, fill=col, r=0.15)
        text(None, 0, 0, 0, 0, [[(Lt, 22, WHITE, True, DISPLAY), (f'　{nm}', 14, WHITE, True)]], shp=top, anchor=MID, margin=0.15, align=L)
        T(s, x + 0.15, 2.5, 2.6, 1.2, ex, 13, TEXT_D, spacing=1.3)
        T(s, x + 0.15, 3.75, 2.6, 0.4, '词：' + wd, 11.5, GREY)
    T(s, 0.7, 4.45, 6, 0.3, '三类内容（每一条证据都要标）', 12, AMBER_D, True)
    kinds = [('事实', '课文写出来的', TEAL), ('作者的判断', '作者下的结论——找判断词', AMBER_D), ('我的推断', '我自己推出来的——写出“还缺什么证据”', CORAL)]
    for i, (k, d, col) in enumerate(kinds):
        x = 0.7 + i * 4.05
        rrect(s, x, 4.8, 3.9, 0.95, fill=col, alpha=14, line=col, r=0.12)
        text(s, x + 0.2, 4.8, 3.6, 0.95, [(k, 16, col, True, DISPLAY), (d, 12, TEXT_D)], anchor=MID, spacing=1.25)
    T(s, 0.7, 5.95, 12, 0.4, '四人组角色（每课轮换）：记录　发言　质疑　计时。质疑者必须问：“这是课文写的，还是你推的？”', 13, TEXT_D)
    timeline(s, [('先立场', 2), ('找证据', 4), ('轮讲', 4), ('全班追问', 5)], cur=None)
    notes(s, '第2步 领场景找证据（4′）：四人组每人负责一个场景，找一条能支持或削弱小组立场的内容，写成一行，并标“事实／作者的判断／我的推断”。教师在课文上标出四个场景的起止。\n第3步 小组轮讲（4′）：质疑者必须问“这是课文写的，还是你推的？”；可以改立场。\n压缩：第2步每组只找一条证据（3′）。\n人数不是4的倍数时，多出的1–2人并入邻组当第5人。')

    # ---- 议·同心圈
    s = new('ink')
    T(s, 0.7, 0.42, 7, 0.3, '第 1 课　议 · 场景 B', 12, AMBER, True)
