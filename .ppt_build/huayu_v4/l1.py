def lesson1():
    cover(1, '声', '华语的声音', '“我没有华文名字。”', '凭这一句，能断定他不认同自己是华人吗？',
          '第1课封面。读通全文；分清“课文写出的事实”“作者的判断”“我的推断”。\n今天的成果：四个场景的概括＋八个词的订正。\n本课 45′ = 开场4′＋读12′＋议15′＋写10′＋出口4′。')

    # ---- 开场：小调查
    s = new('paper')
    chrome(s, '第 1 课　开场', '名字和语言，对你意味着什么？', cur=None, mins=4)
