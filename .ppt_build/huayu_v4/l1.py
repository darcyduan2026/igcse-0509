        num(s, x + 0.2, y + 0.2, 0.55, i + 1, AMBER, 18, INK)
        T(s, x + 0.95, y + 0.2, 4.8, 0.4, k, 16, AMBER, True, DISPLAY)
        T(s, x + 0.25, y + 0.85, 5.4, 1.1, q, 13.5, WHITE, spacing=1.35)
