from common import *


def lesson4():
    lcover(4, '文学表达', '文字怎样写出反抗？', '今天的成果：一份改写实验记录 ＋ 一段鉴赏文字的主体',
           '第4课封面。前三课已经把语言读通，这里不再逐句翻译，而是问“为什么这样写”。注意：本课的原句多数在第2课出现过，要求已经不同——第2课问“什么意思”，今天问“少了它会失去什么”。\n本课 45′ = 开场4′＋读12′＋议15′＋写10′＋出口4′（含同桌反馈）。')
    pages.retrieval(4, [('“俱为贼所执”是什么句式？谁被谁抓？', '被动句（为……所）；夫妇被贼人抓住。'),
                        ('“欲杀其夫而妻之”的“妻”是什么词，作什么用？', '名词作动词，意为“娶她为妻”。'),
                        ('哪一处反抗最能体现李歌的选择？引用一处原文（≤12 字），写出它“写了什么”。（第3课出口原题）', '开放题，如“辄拂袖径出”——有人轻薄对待她，她立刻甩袖径直离开。只写原文写了什么，不写“因此她很勇敢”。')],
                    '开场（3′＋1′）。题3是第3课出口原来的“事实”题，间隔一课再问；若第3课出口第2题（为……所）错误率高，把题1换成新的被动句。')

    # ---- 读①：改写实验
    s = new('paper')
    chrome(s, '第 4 课　读 · 改写实验', '同一个行为，哪一种写法更有力？', cur='读', mins=12)
    orig_box(s, 0.7, 1.55, 6.3, 1.45, '原文：“或有狎之者，辄拂袖径出，弗少留。”', 18)
    rrect(s, 0.7, 3.15, 6.3, 1.45, fill=PAPER2, r=0.04)
    text(s, 0.95, 3.2, 5.8, 1.35, [('改写（教师改写，非原文）', 13, AMBER_D, True), ('“如果有人冒犯她，李歌便离开。”', 18, TEXT_D, False, DISPLAY)], anchor=MID, spacing=1.4)
    for i, (n_, h_, b_, col) in enumerate([('1', '独立标记　2′', '用括号标出：改写句删掉或弱化了原文哪些字？至少 3 处。', TEAL), ('2', '同桌排序　1′', '哪个字对画面或节奏影响最大？排出前二。', AMBER_D), ('3', '举牌辩护　2′', '删掉哪个损失最大？“三二一”同时亮牌，请持不同牌的 2 位辩护。', CORAL)]):
        task_card(s, 7.25, 1.55 + i * 1.5, 5.4, 1.38, n_, h_, b_, col)
    x = 0.7
    for L_, w_, wd in [('A', '辄', 1.2), ('B', '拂袖', 1.5), ('C', '径出', 1.5), ('D', '弗少留', 1.85)]:
        chip(s, x, 4.85, wd, f'{L_}　{w_}', line=CORAL, color=CORAL, size=18, h=0.55); x += wd + 0.15
    T(s, 0.7, 5.55, 6.3, 0.85, '产出：我认为损失最大的是“＿”，因为读者原本会看到／听到＿＿', 15, TEXT_D, True, spacing=1.3)
    timeline(s, [('改写实验', 5), ('动作词表', 7)], cur=0)
    notes(s, '改写实验（5′）：先说清右边是教师改写，不是原文。分析单位是词语与效果，而不是“原文更高级”。\n预期：多数选“辄”或“弗少留”；追问选“径出”的学生：“径”比“出”多了什么？（径直、毫不迂回）。\n这是第2课“只译不评”的承接：今天才问“为什么这样写更有力”。')

    # ---- 读②：动作词表
    s = new('paper')
    chrome(s, '第 4 课　读 · 动作词', '四个短语连起来，人物就动起来了', cur='读', mins=12)
    grid(s, 0.7, 1.5, [1.7, 2.4, 4.1, 3.75], 0.9, ['词', '字面意思', '当读者看到＿，会＿＿，因此＿＿', '参考（点一下）'],
         [['辄', '一遇到就……', '', ''], ['拂袖', '甩动衣袖', '', ''], ['径出', '径直离开', '', ''], ['弗少留', '一点也不停留', '', '']], fs=16, hfs=14, first_bold=True)
    refs = ['一遇到便如此：这是她一贯的做法，不是一时冲动', '动作带情绪，当众表态', '不绕弯、不协商', '不给对方挽回的余地']
    rv = [T(s, 0.7 + 1.7 + 2.4 + 4.1 + 0.1, 2.03 + i * 0.9 + 0.05, 3.55, 0.8, r_, 14, TEAL, True, spacing=1.2, anchor=MID) for i, r_ in enumerate(refs)]
    reveal(s, [rv])
    T(s, 0.7, 5.75, 11.95, 0.6, 'A 填“辄、拂袖”，B 填“径出、弗少留”（4′）；交换检查（2′）。追问一个：原文为什么没有写“先劝告，再离开”？', 14, TEXT_D, spacing=1.3)
    timeline(s, [('改写实验', 5), ('动作词表', 7)], cur=1)
    notes(s, '动作词表（7′）：A填“辄、拂袖”，B填“径出、弗少留”，交换检查，写成“当读者看到＿，会＿＿，因此＿＿”。\n高阶追问：“原文没有写她先劝告再离开”——说明作者把她的拒绝写成“没有商量余地”，而不是“说服对方”。')

    # ---- 议①：领证据
    s = new('paper')
    chrome(s, '第 4 课　议', '作者为什么把最多的“声音”留给与县令对峙的一场？', cur='议', mins=15, size=26)
    cards = [('A', '反问升级', ['“汝纵不能而忍坏之耶？”', '“乃真贼尔！”', '“岂官人耶？”'], '独立标层：行为／判断／身份。把“岂官人耶”改成“你不是官人”，少了什么？', TEAL),
             ('B', '重复', ['“汝即来，汝即来，吾先杀汝而后自杀尔！”', '删去一个“汝即来”（教师删改，非原文）'], '同桌各读一个版本，各打 1–5 分：威慑感、情绪强度、节奏。', AMBER_D),
             ('C', '叙述节奏', ['成长与日常：多句铺叙', '与县令冲突：直接引语、动作、反问', '“居数年”：一笔带过', '遇贼：短句推进到“并杀之”'], '哪里快，哪里慢？', CORAL),
             ('D', '动作词', ['“辄拂袖径出，弗少留”', '（读环节的结论）'], '四个短语连起来，让读者看见什么？', BROWN)]
    for i, (Lt, nm, qs_, task, col) in enumerate(cards):
        x = 0.7 + i * 3.02
        card(s, x, 1.55, 2.88, 4.45)
        top = rrect(s, x, 1.55, 2.88, 0.7, fill=col, r=0.12)
        label(top, [(f'{Lt}  {nm}', 20, WHITE, True, DISPLAY)])
        text(s, x + 0.15, 2.35, 2.6, 2.2, [(q_, 14, TEXT_D) for q_ in qs_], spacing=1.35)
        T(s, x + 0.15, 4.55, 2.6, 1.4, task, 14, col if col != BROWN else TEXT_D, True, spacing=1.3)
    T(s, 0.7, 6.05, 11.95, 0.35, '①领证据 3′（独立，每人一项）　②轮讲 6′（每人 1′30″；质疑者问：这能证明什么，不能证明什么？）', 14, TEXT_D)
    timeline(s, [('领证据', 3), ('轮讲', 6), ('全班追问', 6)], cur=None)
    notes(s, '议（15′）：议题“为什么作者把最多的‘声音’（直接引语）留给与县令对峙的一场？”——这是作者的取舍，不是“事实不重要”。\n①领证据（3′，独立）；②轮讲（6′）：每人1′30″，质疑者追问“这能证明什么，不能证明什么”；③全班追问（6′，下一页）。\nA反问升级的层级：“汝纵不能而忍坏之耶”＝质问行为（你竟忍心败坏风化）；“乃真贼尔”＝做出判断（定性为贼）；“岂官人耶”＝否定身份（连“官”的资格也不给）。反问不是真的问，而是比陈述更强的谴责：把答案推给对方，逼他自己承认。\nB重复造成：节奏逼近、情绪升级、给对方“退路”的时间被压缩。不要断言“她毫无恐惧”：威胁语言本身也可能是恐惧下的虚张声势，原文没有写。\nC可对照：直接引语最多的是第3段；“居数年”只有三个字；结局用短句急促推进。\n提醒：只分析语言，不用“男权意识”等现代标签；不鼓励现实中的暴力威胁。\n压缩：只做A、B、C三项。')

    # ---- 议②：全班追问
    s = new('teal')
    T(s, 0.7, 0.42, 7, 0.3, '第 4 课　议 · 全班追问', 12, AMBER, True)
    tracker(s, '议', 15, dark=True)
    text(s, 0.7, 1.0, 11.8, 2.2, [[('四个证据合起来，', 38, WHITE, True, DISPLAY)], [('作者想让读者……？', 38, AMBER, True, DISPLAY)]], spacing=1.35)
    for i, (h_, b_) in enumerate([('用“篇幅”作证据', '直接引语最多的是哪一段？“居数年”只有几个字？这说明什么？'), ('说出“不能证明什么”', '这些证据能证明作者重视她的抉择，能证明她“毫无恐惧”吗？'), ('写下一句', '“因此作者想让读者＿＿。”要用到至少两个证据。')]):
        x = 0.7 + i * 4.05
        rrect(s, x, 3.5, 3.9, 2.4, fill=INK, alpha=55, line=TEAL_L, r=0.08)
        num(s, x + 0.2, 3.65, 0.55, i + 1, AMBER, 18, INK)
        T(s, x + 0.95, 3.65, 2.8, 0.6, h_, 16, AMBER, True, DISPLAY, anchor=MID)
        T(s, x + 0.25, 4.45, 3.5, 1.4, b_, 15, WHITE, spacing=1.35)
    timeline(s, [('领证据', 3), ('轮讲', 6), ('全班追问', 6)], dark=True, cur=2)
    notes(s, '全班追问（6′）：学生可推断作者最重视她的伦理抉择，但必须用“篇幅”这个证据来支撑；同时要说出“不能证明什么”。\n产出：“因此作者想让读者＿＿”（一句）。')

    # ---- 写①：可检验
    s = new('paper')
    chrome(s, '第 4 课　写', '哪一句是“可检验”的分析句？', cur='写', mins=10)
    sents = [('A', '作者运用动作描写，生动形象地表现了李歌的勇敢。', TEAL), ('B', '“辄拂袖径出，弗少留”连续四个短语，读者看不到她犹豫或协商，因此显出她划界的迅速。', AMBER_D), ('C', '这句话让读者印象深刻。', CORAL)]
    for i, (Lt, t, col) in enumerate(sents):
        x = 0.7 + i * 4.05
        card(s, x, 1.55, 3.9, 2.9)
        top = rrect(s, x, 1.55, 3.9, 0.65, fill=col, r=0.15); label(top, [(Lt, 24, WHITE, True, DISPLAY)])
        T(s, x + 0.2, 2.35, 3.5, 2.0, t, 16, TEXT_D, False, DISPLAY, spacing=1.4)
    T(s, 0.7, 4.65, 11.95, 0.5, '哪一句，读者能回到原文去检验？“三二一”同时举牌。B 句比 A 句多了哪两样？', 16, TEXT_D, True)
    rrect(s, 0.7, 5.25, 11.95, 0.85, fill=PAPER2, r=0.12)
    label(rrect(s, 0.7, 5.25, 11.95, 0.85, fill=None, r=0.12), [('接着写：鉴赏段的主体（7′）→ 自查（2′）', 16, TEXT_D, True)])
    timeline(s, [('可检验句', 1), ('写主体', 7), ('自查', 2)], cur=0)
    notes(s, '答案B：有原文词（辄拂袖径出）＋可检验的效果（读者看不到犹豫）＋指向人物（划界迅速）。A的毛病：没有原文词，“生动形象”“勇敢”都是标签；C的毛病：没有说读者看到什么。')

    # ---- 写②：鉴赏段
    s = new('paper')
    chrome(s, '第 4 课　写', '写一段鉴赏：不要只说“生动形象”', cur='写', mins=10)
    for i, (h_, b_, col) in enumerate([('主张', '哪种语言选择最值得分析？', TEAL), ('证据', '精确引用 1–2 个词或短句。', AMBER_D), ('效果', '这些字制造了怎样的语气或画面？', CORAL), ('意义', '这如何影响我们对李歌的理解？', BROWN)]):
        x = 0.7 + (i % 2) * 6.05; y = 1.55 + (i // 2) * 1.5
        card(s, x, y, 5.9, 1.38)
        num(s, x + 0.2, y + 0.38, 0.62, i + 1, col, 20)
        text(s, x + 1.05, y + 0.08, 4.7, 1.22, [(h_, 18, TEXT_D, True, DISPLAY), (b_, 14, GREY)], anchor=MID, spacing=1.3)
    T(s, 0.7, 4.6, 11.95, 0.4, '选一个分析对象', 14, AMBER_D, True)
    x = 0.7
    for w_ in ['动作词：辄／径出／弗少留', '重复：“汝即来，汝即来”', '反问的升级', '叙述节奏的快与慢']:
        wd = 0.3 + 0.26 * len(w_)
        chip(s, x, 4.95, wd, w_, line=TEAL, color=TEAL, size=14, h=0.45); x += wd + 0.15
    T(s, 0.7, 5.6, 11.95, 0.7, '自查：至少一个精确引用的原文词　一句“读者会……”的效果　一句回到李歌或主题的话。课上写主体，课后补完到 120–160 字（课堂建议，不是考试规定字数）。', 14, TEXT_D, spacing=1.35)
    timeline(s, [('可检验句', 1), ('写主体', 7), ('自查', 2)], cur=1)
    notes(s, '写主体（7′）：弱学生用第3课“细节→立场→局限”的句子框架；强学生加一句“如果删去／改成……会失去什么”。字数120–160字为课堂建议，不是IGCSE官方字数。\n收稿：下课前收上来，只批“有没有原文词”和“有没有写效果”两项，下节课返还；课后补完。')

    # ---- 出口：同桌反馈＋出口
    s = new('paper')
    chrome(s, '第 4 课　出口', '同桌反馈 2′ ＋ 出口 2′', cur='写', mins=4)
    card(s, 0.7, 1.7, 5.9, 4.4)
    top = rrect(s, 0.7, 1.7, 5.9, 0.65, fill=TEAL, r=0.15); label(top, [('同桌反馈　2′', 18, WHITE, True, DISPLAY)])
    for i, t in enumerate(['交换读稿。', '圈出对方一处“浅层判断”，写一条可执行修改：“请把……改成……，加上……”', '作者当场修订一句：必须含具体词语＋效果。']):
        y = 2.55 + i * 1.15
        num(s, 0.95, y + 0.1, 0.55, i + 1, AMBER_D, 16)
        T(s, 1.75, y, 4.7, 1.05, t, 15, TEXT_D, anchor=MID, spacing=1.3)
    card(s, 6.85, 1.7, 5.8, 4.4)
    top = rrect(s, 6.85, 1.7, 5.8, 0.65, fill=CORAL, r=0.15); label(top, [('出口　2′', 18, WHITE, True, DISPLAY)])
    T(s, 7.1, 2.55, 5.3, 0.4, '可检验', 14, AMBER_D, True)
    T(s, 7.1, 2.95, 5.3, 2.6, '把“李歌很勇敢”改写成一句可检验的分析句（含一个原文词和一个效果）。', 18, TEXT_D, False, DISPLAY, spacing=1.5)
    timeline(s, [('同桌反馈', 2), ('出口', 2)], y=6.5)
    notes(s, '出口（4′）：同桌反馈2′＋独立出口2′。原来的“原文词＋效果”“叙述”两题已并入读和议；原提取题改到第5课开场。\n反馈只许是“可执行”的：禁止“多写一点”“再生动些”。常见追问：“作者用了语言描写。”→是哪一句？有什么特别的语气？／“李歌很勇敢。”→哪些词更能证明勇敢，而不只是愤怒？／“让读者印象深刻。”→读者看到什么场景？／“这里运用了反问。”→反问问的是什么？比陈述句多了什么力度？\n把修订前后的两句并排留作学习档案的证据。若第3课出口第1题没写“局限”的学生，请与写了“局限”的同伴配对。')
    pages.exit_key(4, [('同桌反馈', '开放题：修订后的一句必须含具体词语＋效果。'),
                       ('可检验', '例：“辄拂袖径出，弗少留”四个短语连续推进，读者看不到犹豫，因此显出她划界的迅速。')],
                   '第2题未含原文词的学生，第5课写作时用“句式支架”版本。',
                   '1. 把课上写的鉴赏段补完到 120–160 字，按同桌的“可执行修改”订正。\n2. 预习：读一遍结尾“吁！倡犹能有是哉！可慨也。”', '下一课：谁在评价——“倡犹能有是哉”，是赞美，还是带着偏见的赞美？',
                   '1分钟，学生自行订正。')
