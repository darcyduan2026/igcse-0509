def read_page(n, tag, title, orig, words, circle, steps, tl, cur, notes_t):
    s = new('paper')
    chrome(s, f'第 {n} 课　读', title, cur='读', mins=12, size=28)
    orig_box(s, 0.7, 1.55, 7.2, 2.95, orig, 17)
    T(s, 0.7, 4.65, 7.2, 0.9, words, 14, GREY, spacing=1.4)
    T(s, 0.7, 5.5, 3.0, 0.3, '先圈这些词，写下它们的意思：', 14, AMBER_D, True)
    x = 0.7
    for w in circle:
        wd = 0.55 + 0.32 * len(w)
        chip(s, x, 5.85, wd, w, line=CORAL, color=CORAL, size=16, h=0.42)
        x += wd + 0.12
    for i, (n_, h_, b_, col) in enumerate(steps):
        task_card(s, 8.15, 1.55 + i * 1.6, 4.5, 1.45, n_, h_, b_, col)
    timeline(s, tl, cur=cur)
    notes(s, notes_t)
    return s


def cmp_page(n, tag, title, rows, mins, tl, cur, notes_t, cur_phase='议', rowh=1.0, strip=None):
    s = new('paper')
    chrome(s, tag, title, cur=cur_phase, mins=mins, size=28)
    grid(s, 0.7, 1.5, [3.9, 5.0, 3.05], rowh, ['原文', '参考译文', '易错点'], rows, fs=14, hfs=14, first_bold=False)
    if strip:
        T(s, 0.7, 1.5 + 0.53 + rowh * len(rows) + 0.05, 11.95, 0.4, strip, 14, TEXT_D, True)
    timeline(s, tl, cur=cur)
    notes(s, notes_t)
    return s


