# 3 头脑风暴：零散的碎片 → 核心问题
# =====================================================================
s = new('paper'); chrome(s, '第一阶段 · 找素材', '头脑风暴：我们想到了什么？'); mode(s, '全班 · 白板')
sub(s, '课堂上，学生围绕题目提出的素材')
frags = [('火车站', 0.9, 2.0, 2.2, -3), ('儿时好友', 4.0, 2.6, 2.4, 2), ('偶遇时的场景', 7.5, 1.95, 2.9, -2),
         ('帽子', 11.0, 2.7, 1.6, 4), ('影子', 1.8, 3.5, 1.8, 3), ('人影', 5.3, 3.7, 1.8, -4)]
fs_ = []
for (t, x, y, w, r_) in frags:
    f = rrect(s, x, y, w, 0.8, fill=WHITE, line=GREY, r=0.15, dash=True, lw=1.5, rot=r_)
    label(f, [(t, 20, TEXT_D, True, DISPLAY)])
    fs_.append(f)
b1 = rrect(s, 0.7, 4.7, 11.95, 0.6, fill=INK, r=0.1)
label(b1, [('它们是零散的碎片：彼此没有联系，也看不出写作的目的。', 18, WHITE, False, DISPLAY)])
b2 = rrect(s, 0.7, 5.4, 11.95, 0.95, fill=AMBER, r=0.1)
label(b2, [('老师追问：写这些碎片，目的是什么？要体现作者一个关于什么的思想？', 20, INK, True, DISPLAY), ('在白板上写一句话，三、二、一，同时亮板。', 14, INK, False)], spacing=1.25)
reveal(s, [fs_[:3], fs_[3:], [b1], [b2]])
stagebar(s, 0)
notes(s, '【第一阶段：从题目出发找素材 → 发现“零散”】\n这页还原课堂上学生的头脑风暴：火车站、儿时好友、偶遇的场景，以及帽子、影子、人影等具体细节。虚线、微微歪斜的碎片卡片，故意不连线——它们是零散的。点击两次，出齐六个碎片。\n关键动作：先让学生看“零散”这个状态，再问目的。第三次点击出现“零散的碎片：彼此没有联系，也看不出写作的目的”，停一停，让学生自己点头或摇头。\n第四次点击出现追问：写这些碎片，目的是什么？要体现作者一个关于什么的思想？\n全员应答：每人在白板上写一句话，三、二、一同时亮板。老师只数人数、不评对错。\n预期回答：①“想写友情/重逢”；②“想写时间流逝”；③“不知道”。三种都可以出现；重点是学生自己发现：碎片很多，但没有一个“想说的话”把它们串起来。\n注意：此时不要提“成长”，也不要提示答案；主题要从下一页的“灵感”里长出来。\n追问：如果只写“火车站、帽子、影子”，读者读完得到什么？（得到一堆画面，不是一个意思。）\n对应问题1：为什么不能只停留在寻找素材？——素材只是原料，没有“要体现的思想”，它们就只是碎片。\n时间：4 分钟。压缩办法：只收 5 块白板，不逐一点评。')

