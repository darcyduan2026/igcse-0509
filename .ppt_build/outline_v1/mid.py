s = new('teal'); chrome(s, '第二阶段 · 从灵感到主题', '哪一个想法，让碎片有了方向？', dark=True); mode(s, '全班', dark=True)
rrect(s, 0.7, 1.9, 3.4, 2.55, fill=None, line=TEAL_L, r=0.06, dash=True, lw=1.3)
T(s, 0.95, 1.98, 3, 0.35, '零散的碎片', 14, TEAL_L, True)
for i, t in enumerate(['火车站', '儿时好友', '偶遇', '帽子', '影子', '人影']):
    c_ = rrect(s, 0.95 + (i % 2) * 1.55, 2.5 + (i // 2) * 0.62, 1.4, 0.48, fill=None, line=TEAL_L, r=0.3, lw=1.0)
    label(c_, [(t, 14, TEAL_L, False)])
ar1 = shape(s, MSO_SHAPE.RIGHT_ARROW, 4.2, 2.95, 0.5, 0.5, fill=AMBER)
mid_ = rrect(s, 4.8, 1.9, 3.6, 2.55, fill=WHITE, line=AMBER, r=0.06, lw=4)
text(None, 0, 0, 0, 0, [('灵感', 14, AMBER_D, True), ('曾经的霸凌', 32, TEXT_D, True, DISPLAY), ('儿时好友小时候，被人欺负', 15, GREY)], shp=mid_, anchor=MID, margin=0.2, spacing=1.35)
q1 = rrect(s, 0.7, 4.7, 11.95, 0.75, fill=WHITE, line=WHITE, r=0.1)
label(q1, [('老师追问：这样的经历，能体现什么主题？', 20, TEXT_D, True, DISPLAY)])
ar2 = shape(s, MSO_SHAPE.RIGHT_ARROW, 8.5, 2.95, 0.5, 0.5, fill=AMBER)
rt_ = rrect(s, 9.1, 1.9, 3.55, 2.55, fill=CORAL, line=CORAL, r=0.06)
text(None, 0, 0, 0, 0, [('主题', 14, WHITE, True), ('成长', 54, WHITE, True, DISPLAY), ('他面对冲突的反应，变了', 15, WHITE)], shp=rt_, anchor=MID, margin=0.2, spacing=1.2, align=C)
q2 = rrect(s, 0.7, 5.55, 11.95, 0.75, fill=WHITE, line=WHITE, r=0.1)
label(q2, [('老师追问：成长具体体现在哪里？人物经历了什么变化？', 20, TEXT_D, True, DISPLAY)])
reveal(s, [[mid_, ar1], [q1], [rt_, ar2], [q2]])
stagebar(s, [0, 1], dark=True)
notes(s, '【第二阶段：从灵感到主题】\n衔接上一页：碎片很多、没有方向。这一页回答“方向从哪里来”——来自某一个碎片激发的灵感。\n左侧是上一页的碎片（静态，虚线框）。点击 1：出现“灵感：曾经的霸凌”——儿时好友小时候被人欺负。这是学生在头脑风暴中提出的故事内容之一（还有“冲突”）；它不是碎片里最“显眼”的，却是最能产生想法的。\n点击 2：追问“这样的经历，能体现什么主题？”。先请学生说，再点击。预期：友情、勇气、成长、校园暴力。追问：哪一个，能让“火车站重逢”和“小时候被欺负”这两件事连起来？（成长：时间隔开了两件事，人变了。）\n点击 3：出现“成长”。注意说明：成长不是老师给的，是从“霸凌 + 阔别已久”这两个条件里推出来的；换了灵感，主题可能不同。\n点击 4：追问“成长具体体现在哪里？人物经历了什么变化？”——引到下一页。\n预期错误：学生说“主题是霸凌”。追问：霸凌是事件，主题回答“这件事让我们明白了什么”。\n对应问题1：素材不是文章的最终目的；一个能产生想法的素材，才会带出主题。\n时间：5 分钟。压缩办法：点击 1 与 2 合并。')

