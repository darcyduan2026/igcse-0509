s = new('paper'); chrome(s, '第二阶段 · 确定主题', '成长的是谁？怎样被看见？'); mode(s, '同桌 · 说一说')
sub(s, '写作对象要先分清：谁在变？谁在看？')
card(s, 0.7, 1.9, 5.85, 1.3)
T(s, 0.95, 1.97, 3, 0.3, '不是……', 14, GREY, True)
text(s, 0.95, 2.3, 5.4, 0.8, [('写“我”的成长', 26, GREY, False, DISPLAY, None, {'strike': True})], anchor=MID)
card(s, 6.8, 1.9, 5.85, 1.3, line=TEAL)
T(s, 7.05, 1.97, 3, 0.3, '而是……', 14, TEAL, True)
text(s, 7.05, 2.3, 5.4, 0.8, [('写他面对冲突的反应变了', 24, TEXT_D, True, DISPLAY)], anchor=MID)
r1 = rrect(s, 0.7, 3.4, 5.85, 0.85, fill=TEAL, r=0.1)
label(r1, [('他 · 儿时好友：变化的人', 18, WHITE, True, DISPLAY)])
r2 = rrect(s, 6.8, 3.4, 5.85, 0.85, fill=INK, r=0.1)
label(r2, [('我 · 叙述者：见证的人。读者通过“我”的眼睛，看见他的变化', 15, WHITE, False, DISPLAY)], margin=0.2)
T(s, 0.7, 4.4, 8, 0.4, '他的“变”，具体落在哪三处？', 18, TEXT_D, True, DISPLAY)
for i, (ch, q, ex, col) in enumerate([('思想', '他怎么想？', '例：觉得自己无能为力 → 相信自己能解决', TEAL), ('态度', '他怎么对待？', '例：害怕 → 冷静', AMBER_D), ('行为', '他怎么做？', '例：沉默 → 开口表达', CORAL)]):
    x = 0.7 + i * 4.05
    card(s, x, 4.85, 3.85, 1.45)
    o = oval(s, x + 0.15, 5.15, 0.85, 0.85, fill=col); label(o, [(ch, 18, WHITE, True, DISPLAY)], margin=0.0)
    T(s, x + 1.2, 4.92, 2.5, 0.45, q, 18, TEXT_D, True, DISPLAY)
    T(s, x + 1.2, 5.4, 2.55, 0.85, ex, 14, GREY, spacing=1.25)
stagebar(s, 1)
notes(s, '【确定主题：成长——是谁的成长？】\n这一页澄清两个角色，是全课最容易混淆的一点：\n· 他（儿时好友）：变化的人。过去面对霸凌害怕、逃避、沉默；现在面对冲突冷静、勇敢、主动解决。\n· 我（叙述者）：见证的人。我在火车站遇见他，想起他的过去，看见他的现在，并说出我的感受。读者通过“我”的眼睛看见他的变化。\n所以我们写的不是“我长大了”，而是通过“他”的前后不同来体现成长；“我”的作用是见证、回忆和感受。\n同桌活动（1 分钟）：向同桌说一句——“他的变化具体表现在……（思想/态度/行为）”。请 2–3 组分享。\n预期错误：①学生把“我”也写成变化者，两条线混在一起；②只说“他变勇敢了”。追问：勇敢是结果，别人怎么看得出来？他做了什么、说了什么？\n下方三个例子是示例，不是标准答案。\n点出下一步：既然是“变”，就一定需要“变之前”和“变之后”——引到下一页对比。\n时间：3 分钟。')

