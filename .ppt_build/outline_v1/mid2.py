# 4a 写作的目的：没有目的 vs 有了目的
# =====================================================================
s = new('paper'); chrome(s, '第二阶段 · 写作为了什么', '写作的目的，是什么？'); mode(s, '全班')
sub(s, '同样的六个碎片，两种结果')
L_, R_ = [], []
lp = rrect(s, 0.7, 1.9, 5.85, 3.2, fill=WHITE, line=PAST, r=0.05); L_.append(lp)
L_.append(T(s, 0.95, 1.98, 5, 0.4, '没有目的', 17, PAST, True, DISPLAY))
for (t, x, y, r_) in [('火车站', 0.95, 2.6, -3), ('儿时好友', 2.5, 3.25, 2), ('偶遇', 4.4, 2.6, -2), ('帽子', 1.1, 3.85, 3), ('影子', 3.4, 4.0, -3), ('人影', 5.0, 3.35, 3)]:
    c_ = rrect(s, x, y, 1.3, 0.45, fill=PAPER2, line=PAST, r=0.3, dash=True, rot=r_); label(c_, [(t, 14, TEXT_D, True)]); L_.append(c_)
L_.append(T(s, 0.95, 4.55, 5.4, 0.4, '读者读完：只看到一堆画面，不知道你想说什么', 15, TEXT_D, True))
rp = rrect(s, 6.8, 1.9, 5.85, 3.2, fill=WHITE, line=TEAL, r=0.05, lw=2); R_.append(rp)
R_.append(T(s, 7.05, 1.98, 5, 0.4, '有了目的', 17, TEAL, True, DISPLAY))
core = oval(s, 9.0, 3.05, 1.5, 1.5, fill=AMBER); label(core, [('我想让读者明白的一句话', 14, INK, True, DISPLAY)], margin=0.1)
for i, t in enumerate(['火车站', '儿时好友', '偶遇']):
    y = 2.55 + i * 0.7
    R_.append(line(s, 8.4, y + 0.22, 9.05, 3.8, TEAL, 1.5)); c_ = rrect(s, 7.0, y, 1.4, 0.45, fill=WHITE, line=TEAL, r=0.3); label(c_, [(t, 14, TEXT_D, True)]); R_.append(c_)
for i, t in enumerate(['帽子', '影子', '人影']):
    y = 2.55 + i * 0.7
    R_.append(line(s, 11.1, y + 0.22, 10.45, 3.8, TEAL, 1.5)); c_ = rrect(s, 11.1, y, 1.4, 0.45, fill=WHITE, line=TEAL, r=0.3); label(c_, [(t, 14, TEXT_D, True)]); R_.append(c_)
R_.append(core)
R_.append(T(s, 7.05, 4.55, 5.5, 0.4, '读者读完：明白了你想说的话，每个素材都在帮它', 15, TEXT_D, True))
ban = rrect(s, 0.7, 5.3, 11.95, 1.0, fill=INK, r=0.1)
label(ban, [('这句话，就是文章的主题。', 24, AMBER, True, DISPLAY), ('它决定哪些素材留下、哪些删掉、放在哪里。', 16, WHITE, False)], spacing=1.25)
sb = stagebar(s, 0, upto=1)
reveal(s, [L_, R_, [ban, sb[1]]])
notes(s, '【第二阶段：写作为了什么？】\n承接上一页的追问：“写这些碎片，目的是什么？”。先收几块白板，再展示这一页。\n点击 1：左边——没有目的的碎片（虚线、歪斜），读者只看到一堆画面。\n点击 2：右边——同样的六个碎片，但每一个都连向中间的“我想让读者明白的一句话”。\n追问（让学生比较，不要先下结论）：左右两篇，哪一篇读完你知道作者想说什么？为什么？同样的素材，右边多了什么？\n点击 3：点明——这句话，就是文章的主题；它决定哪些素材留下、哪些删掉、放在哪里。（页面底部“2 主题”标签同时出现。）\n注意：这里是让学生通过比较“发现”主题的重要性，而不是先告诉他们“作文要有主题”。\n预期错误：把主题当成题材（“主题是火车站重逢”）。追问：题材是写什么事，主题是通过这件事想让读者明白什么。\n对应问题1：为什么不能只停留在寻找素材？——没有目的的素材只是碎片。\n“留下、删掉、放在哪里”是对主题作用的概括，不是课堂原话，可按需要删改。\n时间：4 分钟。压缩办法：不收白板，直接比较左右。')

